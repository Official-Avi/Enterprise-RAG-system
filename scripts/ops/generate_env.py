#!/usr/bin/env python3
"""Write a new production .env file for RackFlow with freshly generated secrets.

The file sets APP_ENV=production, COOKIE_SECURE=true and DEMO_MODE=false, and generates:

  POSTGRES_PASSWORD          also embedded in DATABASE_URL
  VECTOR_STORE_API_KEY       the API's Qdrant key
  QDRANT__SERVICE__API_KEY   the same key, for the Qdrant server

Everything an operator has to decide stays a placeholder: DOMAIN (and WEB_ORIGIN / API_BASE_URL,
which are https://DOMAIN), TLS_ISSUER, and the MODEL_* settings. Pass --domain and --tls-issuer to
fill the first two. Until DOMAIN is filled the file does not pass the app's production checks, so
the API refuses to start instead of running half-configured.

The file is created with mode 600 where the OS supports it (on Windows, restrict it with the
folder's ACLs). An existing file is never overwritten unless --force is given; with --force it is
replaced atomically. Only the path and the names of the generated values are printed, never the
values. Standard library only, so it runs on a fresh host without the backend virtualenv.

Usage:
  python scripts/ops/generate_env.py --output .env --domain rag.example.com \
      --tls-issuer ops@example.com

Exit codes: 0 written, 1 refused (file exists, or it could not be written), 2 bad arguments.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import secrets
import sys
import tempfile
from pathlib import Path

# 32 random bytes = 256 bits, written as 43 URL-safe base64 characters ([A-Za-z0-9_-]). That
# alphabet needs no escaping in a database URL, a .env file or Compose interpolation (no `$`).
SECRET_BYTES = 32

# Matches the services in docker-compose.yml.
DB_USER = "rackflow"
DB_NAME = "rackflow"
DEFAULT_DB_HOST = "postgres"
DEFAULT_VECTOR_STORE_URL = "http://qdrant:6333"
# The Caddy -> web -> API chain in deploy/compose.prod.yml (the overlay also fixes this value).
COMPOSE_TRUSTED_PROXY_IPS = "172.30.0.10,172.30.0.11"

GENERATED = ("POSTGRES_PASSWORD", "DATABASE_URL (embeds POSTGRES_PASSWORD)", "VECTOR_STORE_API_KEY",
             "QDRANT__SERVICE__API_KEY (same value as VECTOR_STORE_API_KEY)")

_HOST_LABEL = r"(?!-)[A-Za-z0-9-]{1,63}(?<!-)"
_DOMAIN_RE = re.compile(rf"^{_HOST_LABEL}(\.{_HOST_LABEL})*$")
_IPV4_RE = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")
_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
_DB_HOST_RE = re.compile(r"^[A-Za-z0-9.-]+$")


def new_secret() -> str:
    return secrets.token_urlsafe(SECRET_BYTES)


def valid_domain(value: str) -> bool:
    """One host name or IPv4 address: no scheme, port, path or wildcard."""
    if len(value) > 253:
        return False
    if _IPV4_RE.match(value):
        return all(int(part) <= 255 for part in value.split("."))
    return bool(_DOMAIN_RE.match(value))


def valid_tls_issuer(value: str) -> bool:
    return value == "internal" or bool(_EMAIL_RE.match(value))


def render(*, domain: str, tls_issuer: str, db_host: str, postgres_password: str,
           vector_key: str, now: dt.datetime) -> str:
    """The env file's text. Values are written unquoted: every generated one is URL-safe base64."""
    origin = f"https://{domain}" if domain else ""
    stamp = now.strftime("%Y-%m-%dT%H:%M:%SZ")
    return f"""\
# RackFlow AI production environment, generated by scripts/ops/generate_env.py at {stamp}.
# It holds live secrets: never commit it, keep it mode 600, and back it up somewhere safe (losing
# POSTGRES_PASSWORD means resetting it inside Postgres). Every variable is documented in
# deploy/env.production.example.

APP_ENV=production
COOKIE_SECURE=true
DEMO_MODE=false
LOG_LEVEL=INFO

# --- Fill in -------------------------------------------------------------------------------------
# Public host name served by Caddy, e.g. rag.example.com. WEB_ORIGIN and API_BASE_URL must be
# https://DOMAIN; the API refuses to start in production while they are empty.
DOMAIN={domain}
WEB_ORIGIN={origin}
API_BASE_URL={origin}
# An e-mail address (ACME contact for public certificates), or `internal` for Caddy's own CA on a
# test host.
TLS_ISSUER={tls_issuer}

# Chat model. extractive answers by quoting retrieved passages, with no model and no egress.
# For a real model set MODEL_PROVIDER=anthropic (needs MODEL_NAME and MODEL_API_KEY) or
# openai_compatible (needs MODEL_NAME and MODEL_BASE_URL; MODEL_API_KEY and an https:// URL unless
# the endpoint is on a private network).
MODEL_PROVIDER=extractive
MODEL_NAME=
MODEL_BASE_URL=
MODEL_API_KEY=
MODEL_TIMEOUT_SECONDS=60

# --- Generated secrets ---------------------------------------------------------------------------
# POSTGRES_PASSWORD initialises the Postgres volume on its first start only; changing it later does
# not change the database password. DATABASE_URL must carry the same password.
POSTGRES_PASSWORD={postgres_password}
DATABASE_URL=postgresql+psycopg://{DB_USER}:{postgres_password}@{db_host}:5432/{DB_NAME}
# The API's Qdrant key and the Qdrant server's key: the two must be equal.
VECTOR_STORE_URL={DEFAULT_VECTOR_STORE_URL}
VECTOR_STORE_API_KEY={vector_key}
QDRANT__SERVICE__API_KEY={vector_key}

# --- Defaults ------------------------------------------------------------------------------------
VECTOR_COLLECTION=rackflow_chunks
EMBEDDING_PROVIDER=fastembed
EMBEDDING_MODEL=BAAI/bge-small-en-v1.5
# The web /api proxy timeout: API_PROXY_TIMEOUT_MS must equal WEB_PROXY_TIMEOUT_SECONDS * 1000, and
# MODEL_TIMEOUT_SECONDS must stay below it. Caddy's must stay above it.
WEB_PROXY_TIMEOUT_SECONDS=120
API_PROXY_TIMEOUT_MS=120000
CADDY_UPSTREAM_TIMEOUT=180s
# The Compose production overlay fixes this value; it is here for tools that read this file.
TRUSTED_PROXY_IPS={COMPOSE_TRUSTED_PROXY_IPS}
"""


def write_private(path: Path, text: str, *, force: bool) -> None:
    """Create `path` with mode 600. Without `force` an existing file is an error (FileExistsError),
    checked atomically by O_EXCL. With `force` the file is replaced atomically."""
    data = text.encode("utf-8")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    if not force:
        fd = os.open(path, flags, 0o600)
        try:
            os.write(fd, data)
        except BaseException:
            os.close(fd)
            path.unlink(missing_ok=True)
            raise
        os.close(fd)
        _restrict(path)
        return
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as fh:  # mkstemp creates the file with mode 600
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        _restrict(tmp)
        os.replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def _restrict(path: Path) -> None:
    if os.name == "posix":  # elsewhere chmod only toggles the read-only flag
        os.chmod(path, 0o600)


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Write a new production .env file with generated secrets.")
    p.add_argument("--output", required=True, type=Path,
                   help="file to write, e.g. .env next to docker-compose.yml")
    p.add_argument("--domain", default="",
                   help="public host name; also sets WEB_ORIGIN and API_BASE_URL to https://DOMAIN")
    p.add_argument("--tls-issuer", default="",
                   help="ACME contact e-mail, or `internal` for self-signed test certificates")
    p.add_argument("--db-host", default=DEFAULT_DB_HOST,
                   help=f"host in DATABASE_URL (default {DEFAULT_DB_HOST!r}, the Compose service)")
    p.add_argument("--force", action="store_true", help="replace the file if it exists")
    args = p.parse_args(argv)
    args.domain = args.domain.strip().rstrip(".").lower()
    args.tls_issuer = args.tls_issuer.strip()
    if args.domain and not valid_domain(args.domain):
        p.error("--domain must be one host name or IPv4 address, without scheme, port or path")
    if args.tls_issuer and not valid_tls_issuer(args.tls_issuer):
        p.error("--tls-issuer must be an e-mail address or `internal`")
    if not _DB_HOST_RE.match(args.db_host):
        p.error("--db-host must be a host name or IP address")
    return args


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    path: Path = args.output
    if not path.parent.is_dir():
        print(f"error: directory {path.parent} does not exist", file=sys.stderr)
        return 1
    text = render(domain=args.domain, tls_issuer=args.tls_issuer, db_host=args.db_host,
                  postgres_password=new_secret(), vector_key=new_secret(),
                  now=dt.datetime.now(dt.UTC))
    try:
        write_private(path, text, force=args.force)
    except FileExistsError:
        print(f"error: {path} already exists; nothing written. Pass --force to replace it "
              "(its secrets are lost: an initialised Postgres volume keeps the old password).",
              file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"error: cannot write {path}: {exc.strerror or type(exc).__name__}", file=sys.stderr)
        return 1

    print(f"Wrote {path.resolve()}")
    print("Generated (values not shown): " + ", ".join(GENERATED))
    todo = []
    if not args.domain:
        todo.append("DOMAIN, WEB_ORIGIN, API_BASE_URL")
    if not args.tls_issuer:
        todo.append("TLS_ISSUER")
    todo.append("MODEL_* (optional: MODEL_PROVIDER=extractive needs no model)")
    print("Still to fill in: " + "; ".join(todo))
    print("After the stack is up, create the first admin: rackflow-admin bootstrap-admin "
          "--tenant <slug> --tenant-name <name> --email <email> "
          "[--password-env RACKFLOW_ADMIN_PASSWORD]")
    if os.name != "posix":
        print("Note: file mode 600 is not available on this OS; restrict access with ACLs.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
